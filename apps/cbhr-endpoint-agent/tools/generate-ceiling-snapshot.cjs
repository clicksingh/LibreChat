#!/usr/bin/env node
'use strict';

/**
 * CBHR ENDPOINT AGENT — snapshot generator (workstream W7).
 *
 * Reads the SERVER's own ceiling document (`ceilingForStage`) and writes the endpoint's snapshot.
 *
 *   node apps/cbhr-endpoint-agent/tools/generate-ceiling-snapshot.cjs [stage] [--no-pilot] [--out <path>]
 *
 * This tool is deliberately OUTSIDE `src/`: the agent runtime never imports the backend policy
 * module (that would make the endpoint's ceiling a value the endpoint computes for itself, the exact
 * inversion GM-72 forbids). Regeneration is an operator action whose OUTPUT is reviewed and
 * committed, and `tests/dispatch.js` fails when the committed snapshot and a fresh server call
 * disagree — so a policy change cannot reach the endpoint without a visible diff.
 */

const fs = require('node:fs');
const path = require('node:path');

const AGENT_DIR = path.resolve(__dirname, '..');
const REPO_ROOT = path.resolve(AGENT_DIR, '..', '..');
const POLICY_PATH = path.join(REPO_ROOT, 'api', 'server', 'services', 'Device', 'deviceCapabilityPolicy.js');

function usage() {
  return [
    'usage: node tools/generate-ceiling-snapshot.cjs [stage] [--no-pilot] [--out <path>]',
    '',
    '  stage        one of A | B | C | full   (default: A — the read-only stage)',
    '  --no-pilot   drop the pilot deny-list overlay (NOT for the pilot)',
    '  --out        output path (default: config/server-ceiling.json)',
  ].join('\n');
}

function parseArgs(argv) {
  const options = { stage: 'A', pilot: true, out: path.join(AGENT_DIR, 'config', 'server-ceiling.json') };
  for (let index = 0; index < argv.length; index++) {
    const arg = argv[index];
    if (arg === '--no-pilot') {
      options.pilot = false;
    } else if (arg === '--out') {
      index += 1;
      if (argv[index] === undefined) {
        throw new Error('--out requires a path');
      }
      options.out = path.resolve(argv[index]);
    } else if (arg === '--help' || arg === '-h') {
      options.help = true;
    } else if (/^(A|B|C|full)$/.test(arg)) {
      options.stage = arg;
    } else {
      throw new Error(`unrecognised argument: ${arg}`);
    }
  }
  return options;
}

function main() {
  const options = parseArgs(process.argv.slice(2));
  if (options.help) {
    process.stdout.write(`${usage()}\n`);
    return 0;
  }
  if (!fs.existsSync(POLICY_PATH)) {
    process.stderr.write(`cannot find the server policy module at ${POLICY_PATH}\n`);
    return 1;
  }
  // eslint-disable-next-line global-require, import/no-dynamic-require
  const policy = require(POLICY_PATH);
  const ceiling = policy.ceilingForStage(options.stage, { pilot: options.pilot });
  const stageIndex = Object.fromEntries(
    [...policy.TOOL_CATALOG]
      .map((tool) => [tool.name, tool.stage])
      .sort((left, right) => left[0].localeCompare(right[0])),
  );

  const snapshot = {
    $comment:
      'Endpoint snapshot of the SERVER ceiling (GM-72 tier 1). Generated by tools/generate-ceiling-snapshot.cjs from api/server/services/Device/deviceCapabilityPolicy.js. The endpoint never re-derives the ceiling and never widens it; regenerate + review when server policy changes.',
    generatedAt: new Date().toISOString(),
    generatedFrom: 'api/server/services/Device/deviceCapabilityPolicy.js#ceilingForStage',
    requestedStage: options.stage,
    pilot: options.pilot,
    ceiling,
    stageIndex,
    // Rulings that no snapshot may contradict, restated so a hand-edited snapshot is self-refuting.
    rulingAbsoluteDenies: ['track_ui_event', 'give_feedback_to_desktop_commander'],
    deviceSettable: false,
  };

  fs.mkdirSync(path.dirname(options.out), { recursive: true });
  fs.writeFileSync(options.out, `${JSON.stringify(snapshot, null, 2)}\n`, 'utf8');
  process.stdout.write(
    [
      `wrote ${options.out}`,
      `  stage            ${ceiling.stage} (pilot=${ceiling.pilot})`,
      `  ceiling tools    ${ceiling.counts.tools}`,
      `  approval-gated   ${ceiling.counts.approvalRequired}`,
      `  hard-denied      ${ceiling.counts.hardDenied}`,
      `  stage index      ${Object.keys(stageIndex).length} tools`,
      '',
    ].join('\n'),
  );
  return 0;
}

if (require.main === module) {
  try {
    process.exitCode = main();
  } catch (err) {
    process.stderr.write(`generate-ceiling-snapshot failed: ${err.message}\n`);
    process.exitCode = 1;
  }
}

module.exports = { parseArgs, main, POLICY_PATH, AGENT_DIR };